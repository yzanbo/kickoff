// ファイルのタブで選んでいるもの（ファイル・検索・変更の一覧から開く。差分にするかは Git の口 filesGit が決める）

/**
 * 選んでいるファイル。変更の一覧から選んだときは、ステージ済み・未ステージのどちらか（同じファイルが両方にあることもある）。
 * エクスプローラーから選んだときは staged を持たない（変更があっても中身を出し、変更は行の横の色の帯で見せる）。
 * 検索の結果から選んだときは line を持つ（変更があってもいまの中身を出し、その行を目立たせる）。
 * edit は、差分を見ながら編集するとき（変更の一覧から選んだときと、差分の「編集」から来たとき。staged はどちらの差分から来たか。
 * 編集しながらその差分を出す）。focus は「編集」のボタン・右クリックの「新しいファイル」から来たとき（編集の部品にピントを置く。一覧から選んだときは一覧に残し、↑↓ で移れるように）
 */
export interface Selection {
  path: string;
  staged?: boolean;
  line?: number;
  edit?: boolean;
  focus?: boolean;
}

/** 左の一覧の表示（ファイル・検索・変更。プロジェクトのタブの files / search / changes） */
export type ChangesView = "files" | "search" | "changes";
