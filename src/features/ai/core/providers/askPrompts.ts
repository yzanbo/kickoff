/**
 * 名前を付ける・ノートにするため要約する、の頼み方（プロバイダーに依らない。どの AI も ask と同じく 1 回だけ聞く）
 */

/** 要約に渡す文の上限 */
const MAX_SUMMARIZE_CHARS = 60_000;

/** 最初の依頼からチャットの名前を作る頼み */
export const titlePrompt = (text: string) =>
  `次の依頼内容に、20 文字以内の日本語のタイトルを付けてください。タイトルだけを出力し、記号や引用符は付けないでください。\n\n---\n${text.slice(0, 2000)}`;

/** 答えをチャットの名前にする（囲みの引用符を外し、1 行目だけ） */
export const cleanTitle = (answer: string) =>
  answer
    .trim()
    .replace(/^["'「『]|["'」』]$/g, "")
    .split("\n")[0]
    .slice(0, 40);

/** あとで読み返すノートにするため、文を短くまとめる頼み */
export const summarizePrompt = (text: string) =>
  `次の「---」より後ろの文を、あとで読み返すためのノートとして、日本語の Markdown で要点を短くまとめてください。` +
  `文に書いてあることだけを使い、書いていないこと（推測・助言・次にやること・ほかで知っている決まり）は足さないでください。` +
  `大事な決定・理由・手順・名前（ファイル名・コマンドなど）は残してください。短い文なら、ほぼそのままでかまいません。` +
  `前置きや「以下は要約です」などの文は書かず、まとめた本文だけを出力してください。見出し（#）は使わないでください。\n\n---\n${text.slice(0, MAX_SUMMARIZE_CHARS)}`;
